
-- 1. Tabla: company
CREATE TABLE company (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(150) NOT NULL,
    slug VARCHAR(100) NOT NULL,
    status BOOLEAN NOT NULL DEFAULT TRUE,
    
    CONSTRAINT pk_company PRIMARY KEY (company_id),
    CONSTRAINT uk_company_slug UNIQUE (slug)
);

-- 2. Tabla: cafeteria
CREATE TABLE cafeteria (
    cafeteria_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    company_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    time_zone VARCHAR(60) NOT NULL,
    service_start_time TIME NOT NULL,
    service_end_time TIME NOT NULL,
    status BOOLEAN NOT NULL DEFAULT TRUE,
    
    CONSTRAINT pk_cafeteria PRIMARY KEY (cafeteria_id),
    CONSTRAINT fk_cafeteria_company FOREIGN KEY (company_id) 
        REFERENCES company (company_id) ON DELETE RESTRICT,
    CONSTRAINT uk_cafeteria_company_name UNIQUE (company_id, name)
);

-- 3. Tabla: position_type
CREATE TABLE position_type (
    position_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    company_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    sort_order INTEGER NOT NULL,
    status BOOLEAN NOT NULL DEFAULT TRUE,
    
    CONSTRAINT pk_position_type PRIMARY KEY (position_type_id),
    CONSTRAINT fk_position_type_company FOREIGN KEY (company_id) 
        REFERENCES company (company_id) ON DELETE RESTRICT,
    CONSTRAINT uk_position_type_company_name UNIQUE (company_id, name),
    CONSTRAINT chk_position_type_sort_order CHECK (sort_order >= 1)
);

-- 4. Tabla: alert_recipient
CREATE TABLE alert_recipient (
    recipient_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    company_id BIGINT NOT NULL,
    email VARCHAR(150) NOT NULL,
    
    CONSTRAINT pk_alert_recipient PRIMARY KEY (recipient_id),
    CONSTRAINT fk_alert_recipient_company FOREIGN KEY (company_id) 
        REFERENCES company (company_id) ON DELETE RESTRICT
